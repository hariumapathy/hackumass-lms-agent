"""Pydantic row models mirroring the S01 schema (`supabase/migrations/0001_init.sql`).

The SQL migration is the source of truth; these models derive from it. One model per table, field
names identical to column names, so `Model.model_validate(row)` works on `dict_row` results.
`tests/integration/test_s01_schema.py` checks the two stay in sync.
"""

from datetime import datetime
from decimal import Decimal
from typing import Any, Literal
from uuid import UUID

from pydantic import BaseModel

DEFAULT_TIMEZONE = "America/New_York"
EMBEDDING_DIM = 1536

# Enums (Postgres enum types of the same name)
Platform = Literal["canvas", "gradescope", "echo360", "piazza"]
RecordStatus = Literal["active", "changed", "removed"]
ConnectionStatus = Literal["active", "needs_reconnect", "error", "disconnected"]
ItemType = Literal["assignment", "exam", "quiz", "lab", "project", "other"]
MaterialKind = Literal["file", "page", "syllabus", "transcript"]
PostKind = Literal["announcement", "piazza", "email"]
ProcessingStatus = Literal["pending", "processing", "done", "failed", "skipped"]
SyncTrigger = Literal["schedule", "connect", "manual", "agent"]
SyncStatus = Literal["queued", "running", "succeeded", "failed", "needs_reconnect"]
StudySetType = Literal["plan", "quiz", "flashcards"]
StudyBlockStatus = Literal["proposed", "approved", "declined"]
SecretKind = Literal["canvas_token", "storage_state"]
ChangeEntity = Literal["item", "post", "material"]


# --- Identity and connections -----------------------------------------------------------------
class Profile(BaseModel):
    user_id: UUID
    display_name: str | None = None
    timezone: str = DEFAULT_TIMEZONE
    model_choice: str | None = None
    created_at: datetime | None = None


class Connection(BaseModel):
    id: UUID
    user_id: UUID
    platform: Platform
    status: ConnectionStatus = "active"
    expires_at: datetime | None = None
    last_sync_at: datetime | None = None
    last_error: str | None = None
    account_label: str | None = None
    created_at: datetime | None = None


class ConnectionSecret(BaseModel):
    """Never returned by the API or passed to agent code (S10 rule 8)."""

    connection_id: UUID
    revision: UUID
    ciphertext: bytes
    kind: SecretKind
    created_at: datetime | None = None


# --- Courses and course content ---------------------------------------------------------------
class SourceColumns(BaseModel):
    """Common columns on every platform-backed row (S01)."""

    platform: Platform
    platform_id: str
    source_url: str
    content_hash: str
    source_updated_at: datetime | None = None
    last_synced_at: datetime | None = None
    status: RecordStatus = "active"


class Course(BaseModel):
    id: UUID
    user_id: UUID
    name: str
    code: str | None = None
    term: str | None = None
    color: str | None = None
    created_at: datetime | None = None


class CourseLink(SourceColumns):
    id: UUID
    user_id: UUID
    course_id: UUID
    created_at: datetime | None = None


class Item(BaseModel):
    id: UUID
    user_id: UUID
    course_id: UUID
    type: ItemType = "other"
    title: str
    description: str | None = None
    due_at: datetime | None = None
    points: Decimal | None = None
    status: RecordStatus = "active"
    updated_at: datetime | None = None
    created_at: datetime | None = None


class ItemSource(SourceColumns):
    id: UUID
    user_id: UUID
    item_id: UUID | None = None
    course_id: UUID
    raw_title: str
    raw_due_at: datetime | None = None
    raw: dict[str, Any] = {}
    created_at: datetime | None = None


class Material(SourceColumns):
    id: UUID
    user_id: UUID
    course_id: UUID
    kind: MaterialKind
    title: str
    mime_type: str | None = None
    storage_path: str | None = None
    page_count: int | None = None
    duration_s: int | None = None
    recorded_at: datetime | None = None
    version: int = 1
    processing_status: ProcessingStatus = "pending"
    processing_error: str | None = None
    created_at: datetime | None = None


class Post(SourceColumns):
    id: UUID
    user_id: UUID
    course_id: UUID
    kind: PostKind
    title: str
    body: str = ""
    author: str | None = None
    posted_at: datetime
    created_at: datetime | None = None


class Chunk(BaseModel):
    """`tsv` is generated by Postgres and omitted here. `embedding` comes back as a string from
    psycopg unless the pgvector adapter is registered, so it is optional on reads."""

    id: int
    user_id: UUID
    course_id: UUID
    material_id: UUID | None = None
    post_id: UUID | None = None
    material_version: int | None = None
    is_current: bool = True
    text: str
    page: int | None = None
    start_s: int | None = None
    end_s: int | None = None
    token_count: int
    embedding: list[float] | str | None = None
    created_at: datetime | None = None


class Change(BaseModel):
    id: UUID
    user_id: UUID
    entity_type: ChangeEntity
    entity_id: UUID
    course_id: UUID | None = None
    field: str
    old_value: Any = None
    new_value: Any = None
    detected_at: datetime
    seen_at: datetime | None = None
    created_at: datetime | None = None


# --- Agent, study and calendar ----------------------------------------------------------------
class Conversation(BaseModel):
    id: UUID
    user_id: UUID
    title: str
    updated_at: datetime | None = None
    created_at: datetime | None = None


class Message(BaseModel):
    """`content` = `{text, citations[], study_set_ids[], block_ids[]}` (citations resolved, S23)."""

    id: UUID
    user_id: UUID
    conversation_id: UUID
    role: Literal["user", "assistant"]
    content: dict[str, Any] = {}
    created_at: datetime | None = None


class AgentRun(BaseModel):
    id: UUID
    user_id: UUID
    conversation_id: UUID | None = None
    model: str
    status: Literal["running", "done", "error"] = "running"
    turns: int = 0
    tool_calls: list[Any] = []
    allowed_chunk_ids: list[int] = []
    error: str | None = None
    started_at: datetime | None = None
    finished_at: datetime | None = None
    created_at: datetime | None = None


class StudySet(BaseModel):
    id: UUID
    user_id: UUID
    course_id: UUID | None = None
    conversation_id: UUID | None = None
    type: StudySetType
    title: str
    payload: dict[str, Any] = {}
    created_at: datetime | None = None


class StudyBlock(BaseModel):
    id: UUID
    user_id: UUID
    run_id: UUID | None = None
    course_id: UUID | None = None
    item_id: UUID | None = None
    title: str
    start_at: datetime
    end_at: datetime
    status: StudyBlockStatus = "proposed"
    decided_at: datetime | None = None
    created_at: datetime | None = None


class CalendarFeed(BaseModel):
    user_id: UUID
    secret_token: str
    rotated_at: datetime | None = None
    created_at: datetime | None = None


class SyncRun(BaseModel):
    id: UUID
    user_id: UUID
    platform: Platform
    scope: dict[str, Any] = {"kind": "full"}
    trigger: SyncTrigger
    status: SyncStatus = "queued"
    stats: dict[str, int] = {"new": 0, "changed": 0, "unchanged": 0, "removed": 0}
    error: str | None = None
    queued_at: datetime | None = None
    started_at: datetime | None = None
    finished_at: datetime | None = None
    created_at: datetime | None = None


class Miss(BaseModel):
    id: UUID
    user_id: UUID
    tool: str
    query: str
    course_id: UUID | None = None
    created_at: datetime | None = None


# Table name -> row model. Used by the schema-sync test and by generic helpers.
TABLE_MODELS: dict[str, type[BaseModel]] = {
    "profiles": Profile,
    "connections": Connection,
    "connection_secrets": ConnectionSecret,
    "courses": Course,
    "course_links": CourseLink,
    "items": Item,
    "item_sources": ItemSource,
    "materials": Material,
    "posts": Post,
    "chunks": Chunk,
    "changes": Change,
    "conversations": Conversation,
    "messages": Message,
    "agent_runs": AgentRun,
    "study_sets": StudySet,
    "study_blocks": StudyBlock,
    "calendar_feeds": CalendarFeed,
    "sync_runs": SyncRun,
    "misses": Miss,
}
